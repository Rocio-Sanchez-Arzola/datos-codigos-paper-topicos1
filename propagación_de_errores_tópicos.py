# Interpolación de límites a la posición X nominal para graficar la sombra entre los límites de B
y_lim_sup = np.interp(x_r, x_max, y_max)
y_lim_inf = np.interp(x_r, x_min, y_min)

#RMSE y error porcentual de alcance
def rmse(x_sim, y_sim, ts):
    xs = np.interp(t, ts, x_sim); ys = np.interp(t, ts, y_sim)
    return np.sqrt(np.mean((xs - x_exp) ** 2 + (ys - y_exp) ** 2))

err_pct_alcance = abs(np.max(x_exp) - np.max(x_r)) / np.max(x_exp) * 100
