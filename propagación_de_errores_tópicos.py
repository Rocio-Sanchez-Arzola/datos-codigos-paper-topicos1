#VOLEY
ARCHIVO = "volveynuevo2(benja).csv"

#Características de la pelota
m       = 0.279     # Masa de la pelota [kg]
delta_m = 0.001     # Incertidumbre de la balanza [kg]
D       = 0.203     # Diámetro de la pelota [m]
delta_d = 0.001     # Incertidumbre de la cinta métrica [m]
A       = np.pi * (D / 2) ** 2   # Área transversal de la pelota [m^2]
delta_A = A * (2.0 * delta_d / D)
C       = 0.4      #Coeficiente de arrastre
delta_C = 0.05     #Rango de la literatura [0.35, 0.45]
g       = 9.8      #[m/s^2]

#Datos para la densidad del aire
P       = 100080.0  # Presión atmosférica medida [Pa]
delta_P = 10.0     # Precisión del barómetro [Pa]
Temp_C  = 15.0      # Temperatura ambiente medida [°C]
delta_T = 1      # Precisión del termómetro [K o °C]
R_s = 287.058       # Constante específica del aire seco [J/(kg*K)]
T_K = Temp_C + 273  #Conversión temperatura a Kelvin

#Cálculo de densidad e incertidumbre propagada (δρ)
rho = P / (R_s * T_K)
delta_rho = rho * np.sqrt((delta_P / P)**2 + (delta_T / T_K)**2)

#Cálculo de B e incertidumbre propagada (δB)
B = 0.5 * C * rho * A   #Parámetro de arrastre
err_rel_B = np.sqrt((delta_C / C)**2 + (delta_rho / rho)**2 + (delta_A / A)**2)
delta_B = B * err_rel_B
B_min = B - delta_B  #Límite superior de trayectoria
B_max = B + delta_B  #Límite inferior de trayectoria

#Parámetros de simulación y convergencia numérica
N_AJUSTE = 60     # Número de puntos para estimar la velocidad inicial
DT = 0.0005       # Paso de tiempo de Euler [s]
Y_HACIA_ARRIBA = True

print("TERMODINÁMICA Y PROPAGACIÓN DE INCERTIDUMBRES")
print(f"Densidad del aire (ρ) : {rho:.4f} ± {delta_rho:.4f} kg/m³")
print(f"Parámetro de arrastre : B = {B:.6f} ± {delta_B:.6f} kg/m")

#Lectura de datos
df = pd.read_csv(ARCHIVO)
df.columns = ["t", "x_px", "y_px", "vx_app", "vy_app"]
t = df["t"].to_numpy() - df["t"].iloc[0]
x_px = df["x_px"].to_numpy() - df["x_px"].iloc[0]
y_px = df["y_px"].to_numpy() - df["y_px"].iloc[0]
if not Y_HACIA_ARRIBA:
    y_px = -y_px

#Ajuste de escala e incertidumbre asociada
REFERENCIA_PIXELES = 560
REFERENCIA_METROS = 1.75
PX_POR_M = REFERENCIA_PIXELES / REFERENCIA_METROS
x_exp = x_px / PX_POR_M
y_exp = y_px / PX_POR_M
delta_p = 2  # Incertidumbre del clic [px]
err_rel_S = (np.sqrt(2) * delta_p) / REFERENCIA_PIXELES
error_px_m = (REFERENCIA_METROS / REFERENCIA_PIXELES) * delta_p

# Incertidumbre posicional punto a punto en metros
dx_exp = np.sqrt(error_px_m**2 + (x_exp * err_rel_S)**2)
dy_exp = np.sqrt(error_px_m**2 + (y_exp * err_rel_S)**2)

print("INCERTIDUMBRE DE ESCALA Y TRACKING")
print(f"Error base por digitalización (±{delta_p} px): ±{error_px_m * 1000:.2f} mm (±{error_px_m:.4f} m)")
print(f"Incertidumbre relativa de la escala (δS/S): {err_rel_S * 100:.2f} %")
print(f"Incertidumbre posicional promedio en X: ±{np.mean(dx_exp)*1000:.2f} mm (±{np.mean(dx_exp):.4f} m)")
print(f"Incertidumbre posicional promedio en Y: ±{np.mean(dy_exp)*1000:.2f} mm (±{np.mean(dy_exp):.4f} m)")

#Velocidades iniciales
p_x, cov_x = np.polyfit(t[:N_AJUSTE], x_exp[:N_AJUSTE], 2, cov=True)
p_y, cov_y = np.polyfit(t[:N_AJUSTE], y_exp[:N_AJUSTE], 2, cov=True)
vx0 = p_x[1]
vy0 = p_y[1]
delta_vx0 = np.sqrt(cov_x[1, 1])
delta_vy0 = np.sqrt(cov_y[1, 1])
v0 = np.hypot(vx0, vy0)
delta_v0 = np.sqrt((vx0 / v0 * delta_vx0)**2 + (vy0 / v0 * delta_vy0)**2)

print("VELOCIDAD INICIAL E INCERTIDUMBRE ASOCIADA")
print(f"Velocidad inicial vx0 : {vx0:.3f} ± {delta_vx0:.3f} m/s")
print(f"Velocidad inicial vy0 : {vy0:.3f} ± {delta_vy0:.3f} m/s")
print(f"Magnitud total |v0|   : {v0:.3f} ± {delta_v0:.3f} m/s")

#Simulación con Euler para los extremos en base a B
def simular(vx0, vy0, t_max, con_roce=True, b_val=B, dt=DT):
    n = int(t_max / dt) + 1
    ts = np.arange(n) * dt
    x = np.zeros(n); y = np.zeros(n)
    vx = np.zeros(n); vy = np.zeros(n)
    vx[0], vy[0] = vx0, vy0
    b = b_val if con_roce else 0.0
    for i in range(n - 1):
        v = np.hypot(vx[i], vy[i])
        ax = -b * v * vx[i] / m
        ay = -b * v * vy[i] / m - g
        x[i+1]  = x[i]  + vx[i] * dt
        y[i+1]  = y[i]  + vy[i] * dt
        vx[i+1] = vx[i] + ax * dt
        vy[i+1] = vy[i] + ay * dt
    return ts, x, y

t_max = t[-1]

