print(f"Incertidumbre posicional Y promedio : ±{np.mean(dy_exp)*1000:.2f} mm")


#Velocidades iniciales
def simular(vx0, vy0, t_max, con_roce=True, b_val=B, dt=DT):
    n = int(t_max / dt) + 1
    ts = np.arange(n) * dt
    x = np.zeros(n); y = np.zeros(n)
    vx, vy = vx0, vy0
    b = b_val if con_roce else 0.0
    for i in range(n - 1):
        v = np.hypot(vx, vy)
        ax = -b * v * vx / m
        ay = -b * v * vy / m - g
        x[i+1] = x[i] + vx * dt
        y[i+1] = y[i] + vy * dt
        vx += ax * dt
        vy += ay * dt
    return ts, x, y

N = max(8, int(FRAC_AJUSTE * len(t)))

def residuo(p):
    ts, xs, ys = simular(p[0], p[1], t[N-1], con_roce=True)
    return np.r_[np.interp(t[:N], ts, xs) - x_exp[:N],
                 np.interp(t[:N], ts, ys) - y_exp[:N]]

# Ajuste por Mínimos Cuadrados No Lineales
res = least_squares(residuo, [2.5, 4.5])
vx0, vy0 = res.x

#Cálculo de la incertidumbre con el Jacobiano del ajuste de los mínimos cuadrados
J = res.jac
dof = len(res.fun) - len(res.x)
var_residual = np.sum(res.fun**2) / dof
cov_v0 = var_residual * np.linalg.inv(J.T @ J)
delta_vx0 = np.sqrt(cov_v0[0, 0])
delta_vy0 = np.sqrt(cov_v0[1, 1])
v0 = np.hypot(vx0, vy0)
delta_v0 = np.sqrt((vx0 / v0 * delta_vx0)**2 + (vy0 / v0 * delta_vy0)**2)

print("VELOCIDAD INICIAL E INCERTIDUMBRE ASOCIADA")
print(f"Velocidad inicial vx0 : {vx0:.3f} ± {delta_vx0:.3f} m/s")
print(f"Velocidad inicial vy0 : {vy0:.3f} ± {delta_vy0:.3f} m/s")
print(f"Magnitud total |v0|   : {v0:.3f} ± {delta_v0:.3f} m/s")

#Simulaciones nominales y límites de incertidumbre asociados a B
