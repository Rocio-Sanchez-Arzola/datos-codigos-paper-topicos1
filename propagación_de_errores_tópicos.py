if not Y_HACIA_ARRIBA:
    y_px = -y_px

#Ajuste de escala e incertidumbre asociada
REFERENCIA_PIXELES = 767
REFERENCIA_METROS = 1.75
PX_POR_M = REFERENCIA_PIXELES / REFERENCIA_METROS
x_exp = x_px / PX_POR_M
y_exp = y_px / PX_POR_M
delta_p = 2  # Incertidumbre de clic [px]
err_rel_S = (np.sqrt(2) * delta_p) / REFERENCIA_PIXELES
error_px_m = (REFERENCIA_METROS / REFERENCIA_PIXELES) * delta_p

# Incertidumbre posicional punto a punto en metros
dx_exp = np.sqrt(error_px_m**2 + (x_exp * err_rel_S)**2)
dy_exp = np.sqrt(error_px_m**2 + (y_exp * err_rel_S)**2)

